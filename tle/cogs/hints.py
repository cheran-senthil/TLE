"""Graded hints for Codeforces problems.

The hints come from LeekCF Hinter (https://leekcf-hinter-api.leekcf.workers.dev),
a free public API that needs no key. Every problem has 2 to 5 hints, from a small
nudge up to the full solution. An AI model writes them with the official editorial
at hand, so they can be wrong.
"""

import asyncio
import logging
import re
import time
from typing import Any

import aiohttp
import discord
from discord.ext import commands

from tle.util import discord_common

logger = logging.getLogger(__name__)

HINTER_API_URL = 'https://leekcf-hinter-api.leekcf.workers.dev'
_CLIENT_LABEL = 'tle-bot'
_REQUEST_TIMEOUT = aiohttp.ClientTimeout(total=10)
_CACHE_SECONDS = 60 * 60
_CACHE_MAX_ENTRIES = 1000
_MAX_HINT_LENGTH = 3800

_PROBLEM_URL_RE = re.compile(
    r'codeforces\.com/(?:problemset/problem/(\d+)/|contest/(\d+)/problem/)'
    r'([A-Za-z][0-9]?)\b'
)
_PROBLEM_ID_RE = re.compile(r'(\d+)\s*/?\s*([A-Za-z][0-9]?)')
_MATH_RE = re.compile(r'\$+([^$]+?)\$+')

_USAGE = 'Usage: `;hint 1850A`, then `;hint 1850A 2` for the next hint.'
_UNAVAILABLE = 'The hint service is not answering right now. Try again later.'
_RATE_LIMITED = 'Too many hint requests right now. Try again in a minute.'


class HintsCogError(commands.CommandError):
    pass


def parse_problem(text: str) -> tuple[int, str]:
    """Read a problem written as 1850A, 1850 A, 1850/A or a problem link."""
    url = _PROBLEM_URL_RE.search(text)
    if url:
        return int(url.group(1) or url.group(2)), url.group(3).upper()
    match = _PROBLEM_ID_RE.fullmatch(text.strip())
    if match:
        return int(match.group(1)), match.group(2).upper()
    raise HintsCogError(f'That is not a Codeforces problem. {_USAGE}')


def parse_args(args: tuple[str, ...]) -> tuple[int, str, int]:
    """Split the command's arguments into contest id, problem index and hint level."""
    tokens = list(args)
    level = 1
    if len(tokens) > 1 and tokens[-1].isdigit():
        level = int(tokens.pop())
    if not tokens:
        raise HintsCogError(_USAGE)
    if level < 1:
        raise HintsCogError('Hints are numbered from 1.')
    contest_id, index = parse_problem(' '.join(tokens))
    return contest_id, index, level


def format_hint(content: str) -> str:
    """Make a hint readable in Discord: math between $ signs becomes inline code."""
    text = _MATH_RE.sub(lambda m: f'`{m.group(1).strip()}`', content)
    if len(text) > _MAX_HINT_LENGTH:
        text = text[:_MAX_HINT_LENGTH].rstrip()
        if text.count('`') % 2:
            text += '`'
        text += ' …'
    return text


def hint_embed(
    data: dict[str, Any], contest_id: int, index: str, level: int
) -> discord.Embed:
    """One hint, hidden behind a spoiler so the rest of the channel is not spoiled."""
    hints = sorted(data['hints'], key=lambda hint: hint['level'])
    total = len(hints)
    if level == total:
        label = f'Full solution (hint {level} of {total})'
    else:
        label = f'Hint {level} of {total}'
    body = format_hint(hints[level - 1]['content'])
    embed = discord_common.cf_color_embed(
        title=f'{contest_id}{index} - {data["problem"]["name"]}',
        url=f'https://codeforces.com/problemset/problem/{contest_id}/{index}',
        description=f'**{label}**\n||{body}||',
    )
    footer = 'AI-generated by LeekCF Hinter, can be wrong.'
    if level < total:
        footer += f' Next: ;hint {contest_id}{index} {level + 1}'
    embed.set_footer(text=footer)
    return embed


class Hints(commands.Cog):
    def __init__(self, bot: commands.Bot) -> None:
        self.bot = bot
        self._session: aiohttp.ClientSession | None = None
        self._cache: dict[tuple[int, str], tuple[float, dict[str, Any] | None]] = {}

    async def cog_load(self) -> None:
        self._session = aiohttp.ClientSession(timeout=_REQUEST_TIMEOUT)

    async def cog_unload(self) -> None:
        if self._session is not None:
            await self._session.close()

    async def _fetch_hints(self, contest_id: int, index: str) -> dict[str, Any] | None:
        """The API's answer for a problem, or None when it has no hints (yet)."""
        key = (contest_id, index)
        cached = self._cache.get(key)
        if cached is not None and time.monotonic() - cached[0] < _CACHE_SECONDS:
            return cached[1]

        assert self._session is not None, 'Session not initialized.'
        url = f'{HINTER_API_URL}/v1/problems/{contest_id}/{index}/hints'
        try:
            params = {'client': _CLIENT_LABEL}
            async with self._session.get(url, params=params) as resp:
                if resp.status == 404:
                    data = None
                elif resp.status == 200:
                    data = await resp.json()
                elif resp.status == 429:
                    raise HintsCogError(_RATE_LIMITED)
                else:
                    logger.warning(f'LeekCF Hinter answered HTTP {resp.status}')
                    raise HintsCogError(_UNAVAILABLE)
        except (aiohttp.ClientError, asyncio.TimeoutError) as e:
            logger.warning(f'Request to LeekCF Hinter failed: {e!r}')
            raise HintsCogError(_UNAVAILABLE)

        if len(self._cache) >= _CACHE_MAX_ENTRIES:
            self._cache.clear()
        self._cache[key] = (time.monotonic(), data)
        return data

    @commands.command(
        brief='Get a hint for a Codeforces problem', usage='<problem> [hint number]'
    )
    async def hint(self, ctx: commands.Context, *args: str) -> None:
        """Show one hint for a Codeforces problem, hidden behind a spoiler.

        Hints go from a small nudge up to the full solution, so ask for the next one
        only when you are stuck again. Write the problem as 1850A, 1850 A, 1850/A or
        paste its link.
        e.g. ;hint 1850A
             ;hint 1850A 2
        The hints come from the free LeekCF Hinter API. An AI model writes them
        from the official editorial, so they can be wrong.
        """
        contest_id, index, level = parse_args(args)
        data = await self._fetch_hints(contest_id, index)
        if data is None:
            raise HintsCogError(
                f'No hints for {contest_id}{index} yet. Hints usually appear about '
                'a day after a contest ends, once its editorial is out.'
            )
        total = len(data['hints'])
        if level > total:
            raise HintsCogError(
                f'{contest_id}{index} has {total} hints; '
                f'hint {total} is the full solution.'
            )
        await ctx.send(embed=hint_embed(data, contest_id, index, level))

    @discord_common.send_error_if(HintsCogError)
    async def cog_command_error(
        self, ctx: commands.Context, error: commands.CommandError
    ) -> None:
        pass


async def setup(bot: commands.Bot) -> None:
    await bot.add_cog(Hints(bot))
